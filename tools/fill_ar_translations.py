def main() -> None:
    root = Path(__file__).resolve().parents[1]
    po_path = root / "locale" / "ar" / "LC_MESSAGES" / "django.po"
    text = po_path.read_text(encoding="utf-8")
    text = re.sub(r"^#, fuzzy\s*\n", "", text, count=1, flags=re.MULTILINE)

    text = text.replace('"Language: \\n"', '"Language: ar\\n"', 1)

    for en, ar in AR.items():
        pat = "msgid \"" + re.escape(en) + "\"\nmsgstr \"\""
        repl = 'msgid "' + po_escape(en) + '"\nmsgstr "' + po_escape(ar) + '"'
        new_text, n = re.subn(pat, repl, text, count=1)
        if n != 1:
            raise SystemExit(f"Replace failed for msgid={en!r} (matches={n})")
        text = new_text

    po_path.write_text(text, encoding="utf-8")
    print("Updated", po_path)


if __name__ == "__main__":
    main()
